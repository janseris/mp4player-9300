# usage: FFMPEG_SRC=<ffmpeg source dir> python3 gentables.py ../core/m4vtables.h
import os,re,sys
L=os.environ.get('FFMPEG_SRC','ffmpeg')+'/libavcodec/'
def arr(fname, name):
    s=open(L+fname).read()
    m=re.search(r'\b'+re.escape(name)+r'\s*\[[^=]*=\s*\{(.*?)\};', s, re.S)
    if not m: raise SystemExit('missing '+name)
    body=re.sub(r'/\*.*?\*/','',m.group(1),flags=re.S)
    body=re.sub(r'//[^\n]*','',body)
    nums=re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', body)
    return [int(x,0) for x in nums]
out=[]
def emit(ctype,name,vals,per=16):
    out.append('static const %s %s[%d] = {'%(ctype,name,len(vals)))
    for i in range(0,len(vals),per):
        out.append('    '+', '.join(str(v) for v in vals[i:i+per])+',')
    out.append('};')
emit('u8','kIntraMcbpcCode',arr('h263data.c','ff_h263_intra_MCBPC_code'))
emit('u8','kIntraMcbpcBits',arr('h263data.c','ff_h263_intra_MCBPC_bits'))
emit('u8','kInterMcbpcCode',arr('h263data.c','ff_h263_inter_MCBPC_code'))
emit('u8','kInterMcbpcBits',arr('h263data.c','ff_h263_inter_MCBPC_bits'))
emit('u8','kCbpyTab',arr('h263data.c','ff_h263_cbpy_tab'))   # pairs code,len
emit('u8','kMvTab',arr('h263data.c','ff_mvtab'))             # pairs
emit('u16','kInterVlc',arr('h263data.c','ff_inter_vlc'))     # pairs code,len (103)
emit('s8','kInterRun',arr('h263data.c','ff_inter_run'))
emit('s8','kInterLevel',arr('h263data.c','ff_inter_level'))
emit('u8','kDcLum',arr('mpeg4data.h','ff_mpeg4_DCtab_lum'))
emit('u8','kDcChrom',arr('mpeg4data.h','ff_mpeg4_DCtab_chrom'))
emit('u16','kIntraVlc',arr('mpeg4data.h','ff_mpeg4_intra_vlc'))
emit('s8','kIntraRun',arr('mpeg4data.h','ff_mpeg4_intra_run'))
emit('s8','kIntraLevel',arr('mpeg4data.h','ff_mpeg4_intra_level'))
emit('u8','kDefIntraMat',arr('mpeg4data.h','ff_mpeg4_default_intra_matrix'))
emit('u8','kDefInterMat',arr('mpeg4data.h','ff_mpeg4_default_non_intra_matrix'))
emit('u8','kYDcScale',arr('mpeg4data.h','ff_mpeg4_y_dc_scale_table'))
emit('u8','kCDcScale',arr('mpeg4data.h','ff_mpeg4_c_dc_scale_table'))
emit('u8','kDcThreshold',arr('mpeg4data.h','ff_mpeg4_dc_threshold'))
emit('u8','kScanZigzag',arr('mathtables.c','ff_zigzag_direct'))
emit('u8','kScanAltH',arr('mpegvideodata.c','ff_alternate_horizontal_scan'))
emit('u8','kScanAltV',arr('mpegvideodata.c','ff_alternate_vertical_scan'))
hdr='''/* Tables for MPEG-4 Part 2 / H.263 decoding (ISO/IEC 14496-2 Annex B, ITU-T H.263 Annex/Tables).
 * Values as published in the standards; transcribed from FFmpeg's libavcodec tables
 * (h263data.c, mpeg4data.h, mpegvideodata.c, mathtables.c; LGPL-2.1-or-later).
 * Generated by tools/gentables.py - do not edit. */
#ifndef M4VTABLES_H
#define M4VTABLES_H
#include "mpcommon.h"
#define INTRA_RL_LAST 67   /* entries >= this index have last=1 (MPEG-4 intra table) */
#define INTER_RL_LAST 58   /* same for the H.263 inter table */
#define RL_N 102           /* entry 102 is the escape code */
'''
open(sys.argv[1],'w').write(hdr+'\n'.join(out)+'\n#endif\n')
